#!/usr/bin/env bash
# Make the Steam Frame an exact copy of THIS PC's ground station, so it works the same.
#
#   tools/sync-frame.sh [--no-restart] [host]        (host: ssh alias, default "frame")
#
# What it does (nothing here talks to the vehicle):
#   1. rsync the whole tree (code, web, lib submodules, .git, config, docs) to ~/exvectr-gs on the Frame. --delete
#      removes anything on the Frame that is not on the PC, so a missing or stale file cannot survive.
#   2. Builds the Frame's config config/gs.frame.toml from the PC's config/gs.pocket.toml. The ONLY difference is how
#      the Pocket's USB port is matched (the Frame has no /dev/serial/by-id path: vid/pid and the pyusb transport).
#      If that line is not found the script stops, so a config change on the PC can never be silently skipped.
#   3. Reinstalls the Python package on the Frame when pyproject.toml changed.
#   4. Restarts the core on the Frame (unless --no-restart). Do NOT run this while the vehicle is armed or a mission
#      runs: the restart drops the command stream. Reload the browser page on the Frame afterwards.
#
# Not copied: the Frame's .venv, recordings (~/exvectr-recordings), caches, config/gs.local.toml (the old hand-made file).
set -euo pipefail

RESTART=1
if [ "${1:-}" = "--no-restart" ]; then RESTART=0; shift; fi
HOST="${1:-frame}"
cd "$(dirname "$0")/.."
SRC_CFG="config/gs.pocket.toml"
[ -f "$SRC_CFG" ] || { echo "missing $SRC_CFG" >&2; exit 1; }

echo "== commit on this PC: $(git log --oneline -1) ($(git branch --show-current || true))"
if [ -n "$(git status --porcelain --untracked-files=no)" ]; then
  echo "   note: uncommitted changes are copied as they are"
fi

# the Frame's config, from the PC's
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
python3 - "$SRC_CFG" "$TMP" <<'PY'
import re, sys
src, dst = sys.argv[1], sys.argv[2]
text = open(src).read()
pat = re.compile(r'^match = \{ device = "/dev/serial/by-id/usb-Espressif[^"]*" \}[^\n]*$', re.M)
if len(pat.findall(text)) != 1:
    sys.exit("sync-frame: the Pocket 'match = { device = ... Espressif ... }' line of %s was not found exactly once; "
             "update tools/sync-frame.sh to the new config layout" % src)
text = pat.sub('transport = "usb"\nmatch = { vid = "303a", pid = "1001" }', text)
open(dst, "w").write("# GENERATED by tools/sync-frame.sh from gs.pocket.toml (only the Pocket port match differs). Do not edit.\n" + text)
PY

echo "== copying to $HOST:~/exvectr-gs"
ssh "$HOST" 'mkdir -p ~/exvectr-gs'
rsync -a --delete \
  --exclude '.venv/' --exclude '__pycache__/' --exclude '*.pyc' --exclude '.pytest_cache/' --exclude '.ruff_cache/' \
  --exclude '.hypothesis/' --exclude '*.egg-info/' --exclude '.worktrees/' --exclude 'recordings/' \
  --exclude 'config/gs.local.toml*' --exclude 'config/gs.frame.toml' --exclude 'run-frame.sh' \
  ./ "$HOST:exvectr-gs/"
scp -q "$TMP" "$HOST:exvectr-gs/config/gs.frame.toml"

echo "== Python package"
ssh "$HOST" 'bash -s' <<'REMOTE'
set -euo pipefail
cd ~/exvectr-gs
[ -x .venv/bin/pip ] || { echo "no .venv on the Frame: python3 -m venv .venv && .venv/bin/pip install -e ." >&2; exit 1; }
want="$(sha256sum pyproject.toml | cut -d' ' -f1)"
have="$(cat .venv/.pyproject.sha 2>/dev/null || true)"
if [ "$want" != "$have" ]; then
  .venv/bin/pip install -q -e . && echo "$want" > .venv/.pyproject.sha && echo "installed"
else
  echo "up to date"
fi
.venv/bin/python -c "import tomllib; tomllib.load(open('config/gs.frame.toml','rb'))" && echo "config parses"
REMOTE

if [ "$RESTART" = 1 ]; then
  echo "== restarting the core on $HOST"
  ssh "$HOST" 'bash -s' <<'REMOTE'
cd ~/exvectr-gs
for p in $(pgrep -f "[e]xgs core"); do kill "$p"; done
sleep 1.5
DISPLAY=:0 XDG_RUNTIME_DIR=/run/user/1000 setsid nohup .venv/bin/exgs core --config config/gs.frame.toml \
  > /tmp/exgs-core.log 2>&1 < /dev/null &
sleep 6
tail -3 /tmp/exgs-core.log
REMOTE
  echo "done. Reload the page on the Frame (Ctrl+R)."
else
  echo "done (core not restarted)."
fi
