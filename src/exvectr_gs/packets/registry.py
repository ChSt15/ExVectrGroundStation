"""Packet type registry and the `@packet` decorator."""

from __future__ import annotations

import dataclasses
import types
import typing
from collections.abc import Callable
from dataclasses import dataclass
from enum import IntEnum
from typing import TYPE_CHECKING, Any

from .base import Direction, Packet
from .fields import FieldSpec

if TYPE_CHECKING:
    from .textcodec import TextCodec

_RESERVED = ("t", "src", "extra")


@dataclass(frozen=True)
class PacketType:
    name: str
    version: int
    cls: type[Packet]
    fields: tuple[FieldSpec, ...]  # excluding t and src
    direction: Direction
    nominal_rate_hz: float | None  # documentation and staleness default
    history: bool  # keep a time series for trails/plots
    codec: TextCodec
    desc: str = ""

    def field(self, name: str) -> FieldSpec | None:
        for spec in self.fields:
            if spec.name == name:
                return spec
        return None


class PacketRegistry:
    def __init__(self) -> None:
        self._types: dict[str, PacketType] = {}

    def register(self, ptype: PacketType) -> None:
        if ptype.name in self._types:
            raise ValueError(f"packet type {ptype.name!r} already registered")
        self._types[ptype.name] = ptype

    def get(self, name: str) -> PacketType:
        return self._types[name]  # KeyError if unknown

    def all(self) -> list[PacketType]:
        return list(self._types.values())

    def schema(self) -> dict:
        """JSON-serialisable description of all types (sent to clients, protocol section 4.3)."""
        return {"types": [_type_schema(p) for p in self._types.values()]}

    def markdown(self) -> str:
        """Generates docs/packet-types.md. Deterministic."""
        out = [
            "# Packet types",
            "",
            "Generated by `exgs schema --markdown` from the packet registry. Do not edit by hand.",
            "A test fails if this file is out of date.",
            "",
            "All fields are optional (`None` = not supplied by this link) and omitted from log lines then.",
            "Every packet also carries `t` (host receive time, ns since Unix epoch) and `src` (source id).",
            "",
        ]
        for p in self._types.values():
            rate = f"{p.nominal_rate_hz:g} Hz" if p.nominal_rate_hz else "n/a"
            out += [f"## {p.name}", ""]
            if p.desc:
                out += [p.desc, ""]
            out += [
                f"Version {p.version}, direction `{p.direction.value}`, nominal rate {rate}, "
                f"history: {'yes' if p.history else 'no'}.",
                "",
                "| Field | Kind | Unit | Description |",
                "|---|---|---|---|",
            ]
            for s in p.fields:
                kind = s.kind
                if s.length or s.labels:
                    kind += f"[{s.length or len(s.labels)}]"
                if s.enum:
                    kind += f" ({s.enum.__name__}: " + ", ".join(f"{m.name}={m.value}" for m in s.enum) + ")"
                desc = s.desc
                if s.labels:
                    desc = (desc + " " if desc else "") + "Elements: " + ", ".join(s.labels) + "."
                out.append(f"| `{s.name}` | {kind} | {s.unit or '-'} | {desc} |")
            out.append("")
        return "\n".join(out).rstrip("\n") + "\n"


def _type_schema(p: PacketType) -> dict:
    return {
        "name": p.name,
        "version": p.version,
        "direction": p.direction.value,
        "nominal_rate_hz": p.nominal_rate_hz,
        "history": p.history,
        "desc": p.desc,
        "fields": [
            {
                "name": s.name,
                "kind": s.kind,
                "length": s.length,
                "unit": s.unit,
                "enum": [m.name for m in s.enum] if s.enum else [],
                "labels": list(s.labels),
                "desc": s.desc,
            }
            for s in p.fields
        ],
    }


REGISTRY = PacketRegistry()  # populated by importing exvectr_gs.packets.defs


def _infer_kind(name: str, ann: Any) -> tuple[str, type[IntEnum] | None]:
    if typing.get_origin(ann) in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(ann) if a is not type(None)]
        if len(args) != 1:
            raise TypeError(f"field {name}: unsupported union annotation {ann!r}")
        ann = args[0]
    if isinstance(ann, type) and issubclass(ann, IntEnum):
        return "enum", ann
    if ann is bool:
        return "bool", None
    if ann is float:
        return "float", None
    if ann is int:
        return "int", None
    if ann is str:
        return "str", None
    if typing.get_origin(ann) is list:
        (elem,) = typing.get_args(ann)
        if elem is float:
            return "float_array", None
        if elem is int:
            return "int_array", None
    raise TypeError(f"field {name}: unsupported annotation {ann!r}")


def _field_specs(cls: type) -> tuple[FieldSpec, ...]:
    hints = typing.get_type_hints(cls)
    specs = []
    for fld in dataclasses.fields(cls):
        if fld.name in _RESERVED:
            continue
        md = fld.metadata
        kind, enum = _infer_kind(fld.name, hints[fld.name])
        kind = md.get("kind") or kind
        labels = tuple(md.get("labels", ()))
        length = md.get("length") or (len(labels) or None)
        if not kind.endswith("_array"):
            length = None
        specs.append(
            FieldSpec(
                name=fld.name,
                kind=kind,  # type: ignore[arg-type]
                length=length,
                unit=md.get("unit", ""),
                enum=enum,
                optional=md.get("optional", True),
                desc=md.get("desc", ""),
                labels=labels,
            )
        )
    return tuple(specs)


def packet(
    name: str,
    version: int,
    direction: Direction,
    nominal_rate_hz: float | None = None,
    history: bool = False,
    desc: str = "",
    codec: TextCodec | None = None,
    registry: PacketRegistry | None = None,
) -> Callable[[type], type]:
    """Declare a packet type: turns the class into a dataclass and registers it."""

    def deco(cls: type) -> type:
        from .textcodec import GenericTextCodec

        cls = dataclasses.dataclass(kw_only=True, eq=False)(cls)
        cls.TYPE = name  # type: ignore[attr-defined]
        cls.VERSION = version  # type: ignore[attr-defined]
        ptype = PacketType(
            name=name,
            version=version,
            cls=cls,  # type: ignore[arg-type]
            fields=_field_specs(cls),
            direction=direction,
            nominal_rate_hz=nominal_rate_hz,
            history=history,
            codec=codec or GenericTextCodec(),
            desc=desc,
        )
        cls.PTYPE = ptype  # type: ignore[attr-defined]
        (registry or REGISTRY).register(ptype)
        return cls

    return deco
