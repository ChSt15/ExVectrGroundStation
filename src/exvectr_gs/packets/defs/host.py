"""Host-generated packet types (direction LOCAL, never on the wire)."""

from enum import IntEnum

from ..base import Direction, Packet
from ..fields import f
from ..registry import packet


class GsEventKind(IntEnum):
    rec_start = 0
    rec_stop = 1
    source_up = 2
    source_down = 3
    lease_acquired = 4
    lease_released = 5
    lease_expired = 6
    replay_note = 7
    link_warning = 8
    request_sent = 9
    request_retry = 10
    request_ack = 11
    request_timeout = 12


@packet(
    "LinkStats",
    version=1,
    direction=Direction.LOCAL,
    nominal_rate_hz=1,
    history=False,
    desc="Per-source link statistics, generated by the GS at 1 Hz.",
)
class LinkStats(Packet):
    connected: bool = f()
    rx_bytes_s: float = f(unit="B/s")
    rx_frames_s: float = f(unit="1/s")
    tx_frames_s: float = f(unit="1/s")
    crc_errors: int = f()
    decode_errors: int = f()
    reconnects: int = f()


@packet(
    "ConsoleText",
    version=1,
    direction=Direction.LOCAL,
    history=False,
    desc="Non-frame bytes on a serial stream (for example Teensy Serial.print), one line each.",
)
class ConsoleText(Packet):
    text: str = f()


@packet(
    "RawFrame",
    version=1,
    direction=Direction.LOCAL,
    history=False,
    desc="A frame the wire profile could not decode. Kept so that nothing is lost.",
)
class RawFrame(Packet):
    channel: int = f()
    len: int = f()
    hex: str = f()
    err: str = f()


@packet(
    "GsEvent",
    version=1,
    direction=Direction.LOCAL,
    history=False,
    desc="Ground station event (recording, source connection, control lease).",
)
class GsEvent(Packet):
    kind: GsEventKind = f()
    detail: str = f()


@packet("Note", version=1, direction=Direction.LOCAL, history=False, desc="Operator note from the GUI or CLI.")
class Note(Packet):
    text: str = f()
